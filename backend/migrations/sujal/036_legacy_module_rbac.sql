  ('FINANCIAL_REPORT'), ('BILLING'), ('BILLING_CONFIG'), ('INVOICE'), ('BILLING_SCHEDULER'), ('PAYMENT'),
  ('RECONCILIATION'), ('TAX'), ('ACCOUNTING_EXPORT'),
  ('STAFF'), ('STAFF_DOCUMENT'), ('STAFF_UNIT_ASSIGNMENT'), ('STAFF_ATTENDANCE'), ('SHIFT'), ('ROSTER'), ('STAFF_TASK'),
  ('PATROL_CHECKPOINT'), ('PATROL'), ('INCIDENT'), ('EMERGENCY'), ('SECURITY_AUDIT'),
  ('ASSET'), ('ASSET_CATEGORY'), ('ASSET_QR'), ('ASSET_DOCUMENT'), ('ASSET_MAINTENANCE'), ('INVENTORY'),
  ('STOCK_TRANSACTION'), ('AMC'), ('WORK_ORDER'), ('MAINTENANCE_SCHEDULE'), ('ASSET_LIFECYCLE'),
