-- Cross-society administration belongs to Super Admin only. Remove any
-- inherited grants from narrower society personas, including pre-existing
-- template grants, without changing the role or its other permissions.
DELETE FROM role_permissions rp
USING roles r, permissions p
WHERE rp.role_id = r.id
  AND rp.permission_id = p.id
  AND r.society_id IS NULL
  AND r.code <> 'SUPER_ADMIN'
  AND p.module IN ('ORGANIZATION','CLUSTER','SOCIETY_MANAGEMENT','CLUSTER_DASHBOARD','SOCIETY_ACCESS','CLUSTER_REPORT','MULTI_SOCIETY');

