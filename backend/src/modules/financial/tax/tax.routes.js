const express = require("express");

const router =
    express.Router();

const TaxController =
    require("./tax.controller");


/*
|--------------------------------------------------------------------------
| Create Tax Configuration
|--------------------------------------------------------------------------
*/

router.post(
    "/",
    TaxController.createTax
);


/*
|--------------------------------------------------------------------------
| Calculate Generic Tax
|--------------------------------------------------------------------------
*/

router.post(
    "/calculate",
    TaxController.calculateTax
);


/*
|--------------------------------------------------------------------------
| Calculate GST
|--------------------------------------------------------------------------
*/

router.post(
    "/calculate-gst",
    TaxController.calculateGST
);


/*
|--------------------------------------------------------------------------
| Calculate TDS
|--------------------------------------------------------------------------
*/

router.post(
    "/calculate-tds",
    TaxController.calculateTDS
);


/*
|--------------------------------------------------------------------------
| Calculate Invoice Tax
|--------------------------------------------------------------------------
*/

router.post(
    "/calculate-invoice",
    TaxController.calculateInvoiceTax
);


/*
|--------------------------------------------------------------------------
| Get All Taxes
|--------------------------------------------------------------------------
*/

router.get(
    "/",
    TaxController.getAll
);


/*
|--------------------------------------------------------------------------
| Get Tax By ID
|--------------------------------------------------------------------------
*/

router.get(
    "/:id",
    TaxController.getById
);


/*
|--------------------------------------------------------------------------
| Update Tax
|--------------------------------------------------------------------------
*/

router.put(
    "/:id",
    TaxController.updateTax
);


/*
|--------------------------------------------------------------------------
| Deactivate Tax
|--------------------------------------------------------------------------
*/

router.post(
    "/:id/deactivate",
    TaxController.deactivateTax
);


module.exports = router;