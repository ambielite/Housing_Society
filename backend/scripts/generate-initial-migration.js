/* Offline snapshot generator. Does not connect to PostgreSQL. */
require("dotenv").config({ quiet: true });
const fs = require("node:fs");
const path = require("node:path");
const db = require("../src/config/database");
require("../src/config/models");
const q = db.getQueryInterface().queryGenerator;
const models = Object.values(db.models).sort((a, b) => a.tableName.localeCompare(b.tableName));
const enums = [], tables = [], foreignKeys = [], indexes = [], schemaFiles = [];
const tableNames = new Set(models.map(m => m.tableName));
for (const model of models) {
    const enumStart = enums.length, indexStart = indexes.length;
    const attributes = {};
    for (const [name, original] of Object.entries(model.rawAttributes)) {
        const attribute = { ...original };
        const field = attribute.field || name;
        if (attribute.type.key === "ENUM") {
            enums.push("CREATE TYPE " + q.pgEnumName(model.getTableName(), field) +
                " AS ENUM (" + attribute.type.values.map(v => q.escape(v)).join(", ") + ");");
        }
        if (attribute.references) {
            const reference = attribute.references;
            if (!tableNames.has(reference.model)) throw new Error("Unknown reference: " + reference.model);
            foreignKeys.push(q.addConstraintQuery(model.getTableName(), {
                type: "FOREIGN KEY", fields: [field],
                references: { table: reference.model, field: reference.key || "id" },
                onDelete: attribute.onDelete, onUpdate: attribute.onUpdate
            }));
            delete attribute.references;
            delete attribute.onDelete;
            delete attribute.onUpdate;
        }
        attributes[name] = attribute;
    }
    // UUIDV4 is normally generated by Sequelize in JavaScript; supply a SQL default too.
    const sqlAttributes = q.attributesToSQL(attributes, { table: model.getTableName() });
    for (const [name, attribute] of Object.entries(attributes)) {
        if (attribute.defaultValue && attribute.defaultValue.key === "UUIDV4") {
            sqlAttributes[attribute.field || name] += " DEFAULT gen_random_uuid()";
        }
    }
    const sql = q.createTableQuery(model.getTableName(), sqlAttributes, {
        ...model.options, uniqueKeys: model.uniqueKeys
    }).replace("CREATE TABLE IF NOT EXISTS", "CREATE TABLE");
    tables.push("-- " + model.tableName + "\n" + sql);
    for (const index of model.options.indexes || []) {
        indexes.push(q.addIndexQuery(model.getTableName(), {
            ...index,
            fields: index.fields.map(f => typeof f === "string" ? (model.rawAttributes[f]?.field || f) : f)
        }));
    }
    schemaFiles.push({ table: model.tableName, statements: [...enums.slice(enumStart), tables[tables.length - 1], ...indexes.slice(indexStart)] });
}
const directory = path.join(__dirname, "../migrations");
const outputFiles = schemaFiles.map((entry, i) => ({
    name: String(i + 1).padStart(4, "0") + "_create_" + entry.table + ".sql",
    sql: ["-- PostgreSQL 13+. Table: " + entry.table,
        "-- Includes this table's enum types, columns and indexes.",
        ...entry.statements, ""].join("\n\n")
}));
outputFiles.push({
    name: String(outputFiles.length + 1).padStart(4, "0") + "_add_foreign_keys.sql",
    sql: ["-- Add relationships after every referenced table exists.", ...foreignKeys, ""].join("\n\n")
});
for (const file of outputFiles) {
    if (fs.existsSync(path.join(directory, file.name))) throw new Error("Refusing to overwrite " + file.name);
}
for (const file of outputFiles) fs.writeFileSync(path.join(directory, file.name), file.sql, "utf8");
console.log("Generated " + outputFiles.length + " SQL migration files for " + models.length +
    " tables, " + enums.length + " enums, " + foreignKeys.length + " foreign keys and " + indexes.length + " indexes.");
