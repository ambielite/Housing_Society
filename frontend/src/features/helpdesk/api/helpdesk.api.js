import api from '../../../lib/axios';
const unwrap = (r) => r.data.data;
const clean = (p = {}) => Object.fromEntries(Object.entries(p).filter(([,v]) => v !== '' && v !== null && v !== undefined));
// Paths and HTTP methods follow API Reference - Helpdesk, SLA & Escalation (Phase 13).
export const listTickets = (params={}) => api.get('/tickets',{params:clean(params)}).then(unwrap);
export const createTicket = (body) => api.post('/tickets',body).then(unwrap);
export const getTicket = (id) => api.get(`/tickets/${id}`).then(unwrap);
export const updateTicket = (id,body) => api.patch(`/tickets/${id}`,body).then(unwrap);
export const deleteTicket = (id) => api.delete(`/tickets/${id}`).then(unwrap);
export const updateStatus = (id,body) => api.patch(`/tickets/${id}/status`,body).then(unwrap);
export const assignTicket = (id,body) => api.post(`/tickets/${id}/assign`,body).then(unwrap);
export const unassignTicket = (id) => api.patch(`/tickets/${id}/unassign`).then(unwrap);
export const listAssignments = (id) => api.get(`/tickets/${id}/assignments`).then(unwrap);
export const addComment = (id,body) => api.post(`/tickets/${id}/comments`,body).then(unwrap);
export const listComments = (id) => api.get(`/tickets/${id}/comments`).then(unwrap);
export const addAttachment = (id,body) => api.post(`/tickets/${id}/attachments`,body).then(unwrap);
export const listAttachments = (id) => api.get(`/tickets/${id}/attachments`).then(unwrap);
export const listHistory = (id) => api.get(`/tickets/${id}/status-history`).then(unwrap);
export const addRating = (id,body) => api.post(`/tickets/${id}/rating`,body).then(unwrap);
export const listPolicies = (params={}) => api.get('/helpdesk-setup/policies',{params:clean(params)}).then(unwrap);
export const createPolicy = (body) => api.post('/helpdesk-setup/policies',body).then(unwrap);
export const updatePolicy = (id,body) => api.put(`/helpdesk-setup/policies/${id}`,body).then(unwrap);
export const deletePolicy = (id) => api.delete(`/helpdesk-setup/policies/${id}`).then(unwrap);
export const listCategories = (params={}) => api.get('/helpdesk-setup/categories',{params:clean(params)}).then(unwrap);
export const createCategory = (body) => api.post('/helpdesk-setup/categories',body).then(unwrap);
export const updateCategory = (id,body) => api.put(`/helpdesk-setup/categories/${id}`,body).then(unwrap);
export const deleteCategory = (id) => api.delete(`/helpdesk-setup/categories/${id}`).then(unwrap);
export const listRules = (policyId) => api.get(`/helpdesk-setup/policies/${policyId}/escalation-rules`).then(unwrap);
export const createRule = (body) => api.post('/helpdesk-setup/escalation-rules',body).then(unwrap);
export const updateRule = (id,body) => api.put(`/helpdesk-setup/escalation-rules/${id}`,body).then(unwrap);
export const deleteRule = (id) => api.delete(`/helpdesk-setup/escalation-rules/${id}`).then(unwrap);
export const getTimer = (id) => api.get(`/sla/tickets/${id}/timer`).then(unwrap);
export const listEscalations = (id) => api.get(`/sla/tickets/${id}/escalations`).then(unwrap);
export const acknowledgeEscalation = (id) => api.patch(`/sla/escalations/${id}/acknowledge`).then(unwrap);
export const resolveEscalation = (id) => api.patch(`/sla/escalations/${id}/resolve`).then(unwrap);
